export function translate(message, lang = 'en', params = {}) {
  const key = String(message ?? '');
  const localized = lang === 'es' ? (ES[key] || key) : key;
  return localized.replace(/\{(\w+)\}/g, (_, k) => String(params[k] ?? `{${k}}`));
}

const Locale = createContext(null);
export function LocaleProvider({ children }) {
  const [lang, setLang] = useState(() => {
    try { return localStorage.getItem('sh_ui_lang') === 'es' ? 'es' : 'en'; } catch { return 'en'; }
  });
  useEffect(() => {
    document.documentElement.lang = lang;
    try { localStorage.setItem('sh_ui_lang', lang); } catch { /* storage unavailable */ }
  }, [lang]);
  const value = useMemo(() => ({ lang, setLang, t: (key, vars) => translate(key, lang, vars) }), [lang]);
  return <Locale.Provider value={value}>{children}</Locale.Provider>;
}
export function useLocale() {
  const ctx = useContext(Locale);
  if (!ctx) throw new Error('LocaleProvider missing');
  return ctx;
}

// For static JSX text in components without a translation hook. This component
// subscribes directly to locale changes, so profile switches rerender it.
export function Localized({ text, prefix = '', suffix = '' }) {
  const { t } = useLocale();
  return <>{prefix}{t(text)}{suffix}</>;
}
